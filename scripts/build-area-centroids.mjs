// Generates src/lib/market/area-centroids.ts from public/data/uk-postcode-areas.geojson.
//
// One representative point per UK postcode area, used by the Market Explorer's
// "distance from home" ranking. The GeoJSON splits each area into many small
// fragments, so the point is the AREA-WEIGHTED centroid over every fragment
// (shoelace area on a locally cos(lat)-scaled projection) — i.e. the centroid
// of the whole area, not of whichever fragment happens to be biggest.
//
//   node scripts/build-area-centroids.mjs
//
// Run once when the GeoJSON changes; the output is committed.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const geo = JSON.parse(readFileSync(resolve(root, 'public/data/uk-postcode-areas.geojson'), 'utf8'));

function ringCentroid(ring) {
  // Planar shoelace on a locally scaled projection (x = lng·cos(lat0), y = lat).
  const lat0 = ring.reduce((s, [, lat]) => s + lat, 0) / ring.length;
  const k = Math.cos((lat0 * Math.PI) / 180);
  let a = 0, cx = 0, cy = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const [x1, y1] = [ring[i][0] * k, ring[i][1]];
    const [x2, y2] = [ring[i + 1][0] * k, ring[i + 1][1]];
    const f = x1 * y2 - x2 * y1;
    a += f; cx += (x1 + x2) * f; cy += (y1 + y2) * f;
  }
  a *= 0.5;
  if (Math.abs(a) < 1e-12) {
    const lng = ring.reduce((s, [x]) => s + x, 0) / ring.length;
    return { area: 0, lat: lat0, lng };
  }
  return { area: Math.abs(a), lat: cy / (6 * a), lng: cx / (6 * a) / k };
}

const out = {};
for (const f of geo.features) {
  const code = String(f.properties.area).toUpperCase();
  let A = 0, lat = 0, lng = 0;
  for (const poly of f.geometry.coordinates) {
    const c = ringCentroid(poly[0]); // outer ring
    A += c.area; lat += c.lat * c.area; lng += c.lng * c.area;
  }
  if (A === 0) continue;
  out[code] = { lat: Math.round((lat / A) * 1e4) / 1e4, lng: Math.round((lng / A) * 1e4) / 1e4 };
}

const codes = Object.keys(out).sort();
const lines = codes.map((c) => `  ${/^[A-Z]+$/.test(c) ? c : JSON.stringify(c)}: { lat: ${out[c].lat}, lng: ${out[c].lng} },`);
const ts = `/**
 * Representative point (largest-polygon centroid) for every UK postcode area in
 * public/data/uk-postcode-areas.geojson. GENERATED by
 * scripts/build-area-centroids.mjs — do not edit by hand.
 */
export const AREA_CENTROIDS: Record<string, { lat: number; lng: number }> = {
${lines.join('\n')}
};

export function areaCentroid(code: string): { lat: number; lng: number } | null {
  return AREA_CENTROIDS[code.trim().toUpperCase()] ?? null;
}
`;
writeFileSync(resolve(root, 'src/lib/market/area-centroids.ts'), ts);
console.log(`wrote ${codes.length} centroids`);
